def lang_path(current_prefix, target_prefix, page):
    """Ruta relativa desde la carpeta del idioma actual a la página de destino."""
    depth = "../" if current_prefix else ""
    return f"{depth}{target_prefix}{page}"


def canonical_url(prefix, page):
    if page == "index.html":
        return f"{DOMAIN}/{prefix}"
    return f"{DOMAIN}/{prefix}{page}"


def build_hreflang_block(page):
    lines = []
    for l in LANGS:
        href = canonical_url(l["prefix"], page)
        lines.append(f'  <link rel="alternate" hreflang="{l["code"]}" href="{href}" />')
    lines.append(f'  <link rel="alternate" hreflang="x-default" href="{canonical_url("", page)}" />')
    return "\n".join(lines)


def build_lang_options(current_code, page):
    lines = []
    current = LANG_BY_CODE[current_code]
    for l in LANGS:
        path = lang_path(current["prefix"], l["prefix"], page)
        selected = " selected" if l["code"] == current_code else ""
        lines.append(f'            <option value="{path}"{selected}>{l["name"]}</option>')
    return "\n".join(lines)


def render(template_text, tokens):
    def repl(m):
        key = m.group(1)
        if key not in tokens:
            raise KeyError(f"Falta el token {{{{{key}}}}} en las traducciones")
        return tokens[key]
    return re.sub(r"\{\{([A-Z0-9_]+)\}\}", repl, template_text)


def build_page(template_file, page_name, title_key, desc_key):
    template_path = os.path.join(SRC, template_file)
    with open(template_path, "r", encoding="utf-8") as f:
        template_text = f.read()

    for lang in LANGS:
        code = lang["code"]
        prefix = lang["prefix"]
        strings = STRINGS[code]

        tokens = dict(strings)
        tokens["TITLE"] = strings[title_key]
        tokens["DESCRIPTION"] = strings[desc_key]
        tokens["LANG"] = code
        tokens["DIR"] = lang["dir"]
        tokens["BASE"] = "../" if prefix else ""
        tokens["CANONICAL"] = canonical_url(prefix, page_name)
        tokens["HREFLANG_BLOCK"] = build_hreflang_block(page_name)
        tokens["RTL_LINK"] = (
            f'  <link rel="stylesheet" href="{tokens["BASE"]}css/rtl.css" />'
            if lang["dir"] == "rtl" else ""
        )
        tokens["LANG_OPTIONS"] = build_lang_options(code, page_name)
        tokens["CAREERS_SUBJECT"] = quote(strings["CAREERS_SUBJECT"])

        html = render(template_text, tokens)

        out_dir = os.path.join(ROOT, prefix)
        os.makedirs(out_dir, exist_ok=True)
        out_path = os.path.join(out_dir, page_name)
        with open(out_path, "w", encoding="utf-8") as f:
            f.write(html)
        print(f"  {os.path.relpath(out_path, ROOT)}")


